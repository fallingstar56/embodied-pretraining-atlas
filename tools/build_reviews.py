#!/usr/bin/env python3
"""Validate all reviews and generate browser data, audit CSV and a source-linked report."""
import csv
import json
from collections import Counter
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]

def main():
    taxonomy = json.loads((ROOT/'data/annotation_taxonomy.json').read_text())
    reviews = json.loads((ROOT/'data/annotation_reviews.json').read_text())
    with (ROOT/'data/catalog.csv').open(encoding='utf-8-sig', newline='') as f:
        catalog = list(csv.DictReader(f))
    names = [d['数据集'] for d in catalog]
    assert len(names) == len(set(names)) == 117
    assert set(reviews) == set(names), 'Reviews must cover precisely the catalog names'
    labels = {k: {x[0]: x[1] for x in v} for k, v in taxonomy.items()}
    for name, r in reviews.items():
        assert r['status'] in labels['statuses'], name
        assert r['resourceKind'] in labels['resourceKinds'], name
        assert r['note'] and r['checkedAt'] and r['sources'], name
        assert all(urlsplit(u).scheme == 'https' and urlsplit(u).netloc for u in r['sources']), name
        assert len(r['pairs']) == len(set(map(tuple, r['pairs']))), name
        assert all(len(p) == 2 and p[0] in labels['types'] and p[1] in labels['times'] for p in r['pairs']), name
        assert set(r['modalities']) <= {'V', 'L', 'A'}, name
        assert ('A' in r['modalities']) == any(p[0] == 'action_state' for p in r['pairs']), name
        assert r['status'] != 'partial' or r['pending'], name
        assert r['status'] != 'not_applicable' or not r['pairs'], name
    def js(var, obj):
        return '// Generated by tools/build_reviews.py; edit the JSON sources.\nwindow.' + var + ' = ' + json.dumps(obj, ensure_ascii=False, indent=2).replace('</', '<\\/') + ';\n'
    (ROOT/'data/annotation_taxonomy.js').write_text(js('ATLAS_TAXONOMY', taxonomy), encoding='utf-8')
    (ROOT/'data/facet_reviews.js').write_text(js('ATLAS_REVIEWED_FACETS', reviews), encoding='utf-8')
    counts = Counter(r['status'] for r in reviews.values())
    kinds = Counter(r['resourceKind'] for r in reviews.values())
    fmt = lambda r: '；'.join(labels['types'][t]+' @ '+labels['times'][s] for t, s in r['pairs']) or ('不适用' if r['status']=='not_applicable' else '未确认本词表中的标注')
    fields = ['数据集','资源性质','核查状态','标注内容×时间尺度','模态','核查结论','对齐与采样','覆盖范围','待确认','依据URL','核查日期','原目录信号','原目录粒度']
    with (ROOT/'data/annotation_audit.csv').open('w', encoding='utf-8-sig', newline='') as f:
        w = csv.writer(f); w.writerow(fields)
        for d in catalog:
            r = reviews[d['数据集']]
            w.writerow([d['数据集'],labels['resourceKinds'][r['resourceKind']],labels['statuses'][r['status']],fmt(r),'+'.join(r['modalities']),r['note'],r['alignment'],r['scope'],r['pending'],' | '.join(r['sources']),r['checkedAt'],d['训练可用信号'],d['语言/时间粒度']])
    lines = ['# 117 条资源的标注核查记录', '', '核查日期：2026-10-28。覆盖全部目录条目，依据官方项目页、数据卡、论文和公开 schema；没有下载并解析全部原始样本。此处核查的是标注内容及时间尺度，不是许可证、全量质量、可下载规模或去重审计。', '',
             '117 是资源记录数，并非 117 套互不重叠的独立数据集。', '',
             '状态：'+'；'.join(f'{labels["statuses"][k]} {v}' for k,v in counts.items())+'。', '',
             '性质：'+'；'.join(f'{labels["resourceKinds"][k]} {v}' for k,v in kinds.items())+'。', '',
             '分类是“内容 × 时间”的实际配对，不能取两个独立标签集合的笛卡尔积。集合/衍生集列的是已知子集的并集，不保证每个样本具备所有字段。原目录文本保留作对照，不参与自动推断。', '',
             '关键修正：动作采样率不等于语言频率；阶段文字广播到帧仍为阶段；人体/手持夹爪运动与机器人动作分开；ASR、动作类名与视觉描述分开；工具/目录不继承下游标注；ProcCorpus 与 DeMiAn 按已发布衍生数据收录。', '',
             '本轮没有足够证据将任何条目列为固定 1 Hz 标注或严格的单步 next_step 语言。空筛选结果是保守证据结论，不是宣称这类数据不存在。', '',
             '## 时间尺度定义', '', '| 编码 | 名称 | 判定规则 |', '|---|---|---|']
    lines += ['| '+' | '.join(x)+' |' for x in taxonomy['times']]
    lines += ['', '## 标注内容定义', '', '| 编码 | 名称 | 判定规则 |', '|---|---|---|']
    lines += ['| '+' | '.join(x)+' |' for x in taxonomy['types']]
    lines += ['', '## 待确认项', '']
    lines += [f'- **{name}**：{r["pending"]}' for name,r in reviews.items() if r['pending']]
    lines += ['', '## 逐条核查', '']
    for i,d in enumerate(catalog,1):
        name=d['数据集']; r=reviews[name]
        lines += [f'### {i:03d}. {name}', '', f'**{labels["resourceKinds"][r["resourceKind"]]} · {labels["statuses"][r["status"]]}**', '', '**分类：** '+fmt(r), '', r['note'], '']
        for key,title in [('alignment','对齐与采样'),('scope','覆盖范围'),('pending','待确认')]:
            if r[key]: lines += [f'**{title}：** {r[key]}', '']
        lines += ['**依据：** '+' · '.join(f'[来源 {j}]({u})' for j,u in enumerate(r['sources'],1)), '', '**原目录粒度（保留对照）：** '+d['语言/时间粒度'], '']
    (ROOT/'ANNOTATION_AUDIT.md').write_text('\n'.join(lines), encoding='utf-8')
    print('Validated 117 reviews:', dict(counts), dict(kinds))

if __name__ == '__main__':
    main()
